"""Validate Sand Valley CSVs and rebuild the transactional SQL seed (Python stdlib only)."""
import csv
from pathlib import Path

DATA = Path(__file__).resolve().parent

def read(name):
    with (DATA / name).open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))

def quote(value):
    return "NULL" if value == "" else "'" + str(value).replace("'", "''") + "'"

def array(values):
    return "ARRAY[" + ",".join(str(v) if v != "" else "NULL" for v in values) + "]::integer[]"

def build():
    courses = read("sand-valley-course-seed.csv")
    tees = read("sand-valley-course-tee-seed.csv")
    expected = {"Sand Valley": (18, 72), "Mammoth Dunes": (18, 73), "Sedge Valley": (18, 68),
                "The Lido": (18, 72), "Sand Valley (Sandbox)": (17, 51), "Sand Valley (Commons)": (12, 45)}
    assert len(courses) == 6 and {c["course_name"] for c in courses} == set(expected)
    assert len(tees) == 73
    assert len({(t["course_key"], t["tee_name"], t["gender"]) for t in tees}) == len(tees)
    assert {t["course_name"] for t in tees} == set(expected)
    course_values = []
    for c in courses:
        name = c["course_name"]
        count, par = expected[name]
        pars = [int(c[f"hole_{n}_par"]) for n in range(1, count + 1)]
        hcps = [int(c[f"hole_{n}_hcp"]) if c[f"hole_{n}_hcp"] else "" for n in range(1, count + 1)]
        assert sum(pars) == par and all(p in (3, 4, 5) for p in pars)
        assert all(c[f"hole_{n}_{suffix}"] == "" for n in range(count + 1, 19) for suffix in ("par", "hcp"))
        if name.endswith("(Sandbox)"):
            assert hcps == [""] * 17
        else:
            assert sorted(hcps) == list(range(1, count + 1))
        assert c["pcc_default"] == "0" and c["state"] == "WI" and c["city"] == "Nekoosa"
        matches = [t for t in tees if t["course_name"] == name]
        keys = {t["course_key"] for t in matches}
        assert len(keys) == 1
        default = next(t for t in matches if t["tee_name"] == c["target_tee"] and t["gender"] == c["gender"])
        assert c["course_rating"] == default["course_rating"] and c["slope_rating"] == default["slope_rating"]
        course_values.append("(" + ", ".join([quote(next(iter(keys))), quote(name), quote(c["city"]), quote(c["state"]), array(pars), array(hcps)]) + ")")
    rated = []
    for t in tees:
        assert t["source_url"].startswith(("https://cdn.prod.website-files.com/", "https://www.sandvalley.com/"))
        if t["total_yards"]:
            assert 1000 < int(t["total_yards"]) < 8000
        if not t["course_rating"]:
            assert t["course_name"] in ("Sand Valley (Sandbox)", "Sand Valley (Commons)")
            assert t["slope_rating"] == "" and t["gender"] == ""
            continue
        assert 50 < float(t["course_rating"]) < 90 and 55 <= int(t["slope_rating"]) <= 155
        assert t["gender"] in ("M", "F")
        # Database requires a non-null tee_color; empty string means not published.
        columns = [quote(t[k]) if k != "tee_color" or t[k] else "''" for k in
                   ("course_key", "course_name", "tee_name", "tee_color", "gender", "course_rating", "slope_rating", "total_yards", "source_url")]
        rated.append("(" + ", ".join(columns) + ")")
    assert len(rated) == 68
    sql = """-- Sand Valley resort: 6 courses, 101 actual holes, 68 rated tee rows.
-- Generated by data/build-sand-valley-seed.py; verified against official sources 2026-09-19.
-- Requires the saved-course tables and unique keys from supabase-multi-foursome.sql.
-- Sandbox/Commons unrated tee yardages remain in CSV: database ratings are NOT NULL.
-- No invented holes, ratings or handicap indexes. Sandbox indexes remain NULL.
-- Data-only seed; the app currently assumes 18-hole rounds (see data/README.md).
-- Each statement includes its seed data; no temporary tables or session state required.
BEGIN;
"""
    seed_cte = "WITH sand_valley_course_seed(course_key, course_name, city, state, pars, hcps) AS (VALUES\n" + ",\n".join(course_values) + ")\n"
    sql += seed_cte + """
INSERT INTO public.saved_courses (source_provider, source_course_id, name, normalized_name, city, state, updated_at)
SELECT 'manual_seed', course_key, course_name, course_key, city, state, now()
FROM sand_valley_course_seed
ON CONFLICT (normalized_name, city, state) DO UPDATE SET
  source_provider = EXCLUDED.source_provider, source_course_id = EXCLUDED.source_course_id,
  name = EXCLUDED.name, updated_at = now();

-- Separate statement ensures newly inserted courses are visible on the first run.
""" + seed_cte + """
INSERT INTO public.saved_course_holes (saved_course_id, hole_number, par, handicap_index, updated_at)
SELECT c.id, h.n, s.pars[h.n], s.hcps[h.n], now()
FROM sand_valley_course_seed s
JOIN public.saved_courses c ON c.normalized_name = s.course_key AND c.city = s.city AND c.state = s.state
CROSS JOIN LATERAL generate_subscripts(s.pars, 1) AS h(n)
ON CONFLICT (saved_course_id, hole_number) DO UPDATE SET
  par = EXCLUDED.par, handicap_index = EXCLUDED.handicap_index, updated_at = now();

-- Remove only the superseded simulator-only labels from the previous national seed.
DELETE FROM public.saved_course_tees
WHERE ((course_key = 'sand-valley' AND source_url = 'https://simulatorgolftour.com/tournament/27240')
    OR (course_key = 'mammoth-dunes' AND source_url = 'https://simulatorgolftour.com/tournament/16107'))
  AND tee_name IN ('Blue', 'White') AND gender = 'M';

INSERT INTO public.saved_course_tees
  (course_key, course_name, tee_name, tee_color, gender, course_rating, slope_rating, total_yards, source_url)
VALUES
""" + ",\n".join(rated) + ";PLACEHOLDER"
    sql = sql.replace(";PLACEHOLDER", """
ON CONFLICT (course_key, tee_name, gender) DO UPDATE SET
  course_name = EXCLUDED.course_name, tee_color = EXCLUDED.tee_color,
  course_rating = EXCLUDED.course_rating, slope_rating = EXCLUDED.slope_rating,
  total_yards = EXCLUDED.total_yards, source_url = EXCLUDED.source_url, updated_at = now();

""" + seed_cte + """
SELECT s.course_name, count(h.id) AS saved_holes
FROM sand_valley_course_seed s
JOIN public.saved_courses c ON c.normalized_name = s.course_key AND c.city = s.city AND c.state = s.state
JOIN public.saved_course_holes h ON h.saved_course_id = c.id
GROUP BY s.course_name ORDER BY s.course_name;
COMMIT;
""")
    (DATA / "sand-valley-course-seed.sql").write_text(sql, encoding="utf-8", newline="\n")
    print("Validated 6 courses, 101 holes, 73 CSV tee rows; generated SQL with 68 rated tees.")

if __name__ == "__main__":
    build()
